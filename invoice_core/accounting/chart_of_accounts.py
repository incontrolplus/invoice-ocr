class ChartOfAccountsCatalog:
    """Registry and lookup manager for the Bulgarian National Chart of Accounts."""

    def __init__(self, accounts: Iterable[AccountDefinition] | None = None):
        self._accounts: dict[str, AccountDefinition] = {}
        for acc in (accounts if accounts is not None else _RAW_ACCOUNTS):
            self._accounts[acc.code] = acc

    def get(self, code: str) -> AccountDefinition | None:
        """Lookup an account by its code (e.g. '601', '6012', '4531')."""
        if not code:
            return None
        clean_code = str(code).strip().replace("/", "")
        if clean_code in self._accounts:
            return self._accounts[clean_code]
        # Try synthetic prefix (e.g. '6012' -> '601')
        if len(clean_code) > 3 and clean_code[:3] in self._accounts:
            return self._accounts[clean_code[:3]]
        return None

    def exists(self, code: str) -> bool:
        """Check if an account code exists in the catalog."""
        return self.get(code) is not None

    def search(self, query: str, limit: int = 20) -> list[AccountDefinition]:
        """Search accounts by code, name, keywords, or purpose text."""
        if not query or not query.strip():
            return list(self._accounts.values())[:limit]

        tokens = [t.lower() for t in re.split(r"\s+", query.strip()) if t]
        matched: list[tuple[int, AccountDefinition]] = []

        for acc in self._accounts.values():
            score = 0
            code_lower = acc.code.lower()
            name_lower = acc.name.lower()
            purpose_lower = acc.purpose.lower()
            keywords_joined = " ".join(acc.keywords).lower()

            for token in tokens:
                if token == code_lower:
                    score += 100
                elif code_lower.startswith(token):
                    score += 50
                elif token in name_lower:
                    score += 30
                elif token in keywords_joined:
                    score += 25
                elif token in purpose_lower:
                    score += 10

            if score > 0:
                matched.append((score, acc))

        matched.sort(key=lambda x: x[0], reverse=True)
        return [item[1] for item in matched[:limit]]

    def get_by_class(self, account_class: int | AccountClass) -> list[AccountDefinition]:
        """Get all accounts belonging to a specific class (1-9)."""
        cls_val = account_class.value if isinstance(account_class, AccountClass) else int(account_class)
        return [acc for acc in self._accounts.values() if acc.account_class == cls_val]

    def get_by_type(self, account_type: AccountType) -> list[AccountDefinition]:
        """Get all accounts of a specific type (Active, Passive, etc.)."""
        return [acc for acc in self._accounts.values() if acc.account_type == account_type]

    def get_subaccounts(self, synthetic_code: str) -> list[AccountDefinition]:
        """Get all registered subaccounts of a synthetic account."""
        clean = str(synthetic_code).strip()
        return [acc for acc in self._accounts.values() if acc.parent_code == clean]

    def explain(self, code: str) -> str:
        """Provide a formatted Bulgarian explanation of an account's purpose and usage."""
        acc = self.get(code)
        if not acc:
            return f"Сметка {code} не е намерена в Националния сметкоплан."

        type_bg = {
            AccountType.ACTIVE: "Активна сметка",
            AccountType.PASSIVE: "Пасивна сметка",
            AccountType.ACTIVE_PASSIVE: "Активно-пасивна (разчетна) сметка",
            AccountType.OFF_BALANCE: "Задбалансова сметка",
        }.get(acc.account_type, acc.account_type.value)

        lines = [
            f"Сметка {acc.code} – {acc.name}",
            f"Клас: {acc.account_class} | Група: {acc.group_code} | Характер: {type_bg}",
            f"Предназначение: {acc.purpose}",
            f"Дебит: {acc.typical_debit}",
            f"Кредит: {acc.typical_credit}",
        ]
        if acc.subaccounts:
            lines.append(f"Подсметки: {', '.join(acc.subaccounts)}")
        return "\n".join(lines)

    def all_accounts(self) -> list[AccountDefinition]:
        """Return all registered accounts ordered by code."""
        return sorted(self._accounts.values(), key=lambda a: a.code)

    def to_dict_list(self) -> list[dict[str, Any]]:
        """Export all accounts as list of dictionaries."""
        return [acc.to_dict() for acc in self.all_accounts()]


# Default singleton instance
DEFAULT_CHART_OF_ACCOUNTS = ChartOfAccountsCatalog()


def lookup_account(code: str) -> AccountDefinition | None:
    """Convenience helper to look up an account by code."""
    return DEFAULT_CHART_OF_ACCOUNTS.get(code)


def search_accounts(query: str, limit: int = 20) -> list[AccountDefinition]:
    """Convenience helper to search accounts."""
    return DEFAULT_CHART_OF_ACCOUNTS.search(query, limit=limit)


def explain_account(code: str) -> str:
    """Convenience helper to get detailed Bulgarian explanation of an account."""
    return DEFAULT_CHART_OF_ACCOUNTS.explain(code)
