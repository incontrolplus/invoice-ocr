"""Official Bulgarian National Chart of Accounts (НСС / Национален сметкоплан).

Provides comprehensive catalog of standard Bulgarian accounting accounts,
their synthetic and analytical subaccounts, descriptions, legal purposes,
and typical debit/credit debiting/crediting conventions according to the
Bulgarian Accountancy Act (Закон за счетоводството) and National Accounting
Standards (НСС).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
import re
from typing import Any, Iterable


class AccountType(str, Enum):
    """Bulgarian accounting account type."""
    ACTIVE = "active"                   # Активна сметка (увеличава се с дебит, намалява с кредит)
    PASSIVE = "passive"                 # Пасивна сметка (увеличава се с кредит, намалява с дебит)
    ACTIVE_PASSIVE = "active_passive"   # Активно-пасивна сметка (разчетна сметка)
    OFF_BALANCE = "off_balance"         # Задбалансова сметка


class AccountClass(int, Enum):
    """Bulgarian chart of accounts classes (1-9)."""
    CLASS_1_CAPITAL = 1                 # Клас 1: Сметки за капитали
    CLASS_2_NON_CURRENT_ASSETS = 2      # Клас 2: Сметки за дълготрайни активи
    CLASS_3_INVENTORY = 3               # Клас 3: Сметки за материални запаси
    CLASS_4_PAYABLES_RECEIVABLES = 4    # Клас 4: Сметки за разчети
    CLASS_5_FUNDS = 5                   # Клас 5: Сметки за финансови средства
    CLASS_6_EXPENSES = 6                # Клас 6: Сметки за разходи
    CLASS_7_REVENUES = 7                # Клас 7: Сметки за приходи
    CLASS_9_OFF_BALANCE = 9             # Клас 9: Задбалансови сметки


@dataclass(frozen=True)
class AccountDefinition:
    """Detailed definition of a Bulgarian accounting account or subaccount."""
    code: str                           # Номер на сметката (напр. '601', '6012', '401')
    name: str                           # Наименование на сметката
    account_class: int                  # Клас на сметката (1-9)
    group_code: str                     # Група (напр. '60', '40', '30')
    account_type: AccountType           # Активна / Пасивна / Активно-пасивна / Задбалансова
    purpose: str                        # Законово предназначение и описание на операциите
    typical_debit: str                  # Типични дебитни операции (какво се отчита по Дебита)
    typical_credit: str                 # Типични кредитни операции (какво се отчита по Кредита)
    is_synthetic: bool = True           # Синтетична (True) или аналитична/подсметка (False)
    parent_code: str | None = None      # Код на сметката майка (за подсметки)
    subaccounts: tuple[str, ...] = ()   # Списък с кодове на аналитични подсметки
    keywords: tuple[str, ...] = ()      # Ключови думи за автоматично класифициране

    def to_dict(self) -> dict[str, Any]:
        """Convert account definition to JSON-serializable dictionary."""
        return {
            "code": self.code,
            "name": self.name,
            "account_class": self.account_class,
            "group_code": self.group_code,
            "account_type": self.account_type.value,
            "purpose": self.purpose,
            "typical_debit": self.typical_debit,
            "typical_credit": self.typical_credit,
            "is_synthetic": self.is_synthetic,
            "parent_code": self.parent_code,
            "subaccounts": list(self.subaccounts),
            "keywords": list(self.keywords),
        }


